Route::get('/', [HomeController::class, 'index'])->name('home');

// Generic landing point after login — sends each role to its own home.
// If the starter kit already defines a "dashboard" route, replace its
// contents with this instead of adding a second one.
Route::middleware('auth')->get('/dashboard', function () {
    $user = auth()->user();

    return match (true) {
        $user->isAdmin() => redirect()->route('admin.dashboard'),
        $user->isCashier() => redirect()->route('cashier.counter'),
        default => redirect()->route('passenger.book'),
    };
})->name('dashboard');

// ---- Admin -----------------------------------------------------------------
// Report's Admin Module: Dashboard, Manage Users, Manage Routes, Manage Trips,
// Manage Buses, Manage Bookings, Generate Reports.

Route::middleware(['auth', 'role:admin'])->prefix('admin')->name('admin.')->group(function () {
    Route::get('/', AdminDashboard::class)->name('dashboard');
    Route::get('/trips', TripManager::class)->name('trips');
    Route::get('/reports', AdminReports::class)->name('reports');

    Route::resource('parks', ParkController::class)->except(['show']);
    Route::resource('routes', TripRouteController::class)->except(['show']);
    Route::resource('vehicles', VehicleController::class)->except(['show']);
    Route::resource('drivers', DriverController::class)->except(['show']);
    Route::resource('users', UserController::class)->except(['show']);

    Route::get('/bookings', [BookingController::class, 'index'])->name('bookings.index');
    Route::post('/bookings/{booking}/cancel', [BookingController::class, 'cancel'])->name('bookings.cancel');
});

// ---- Cashier -----------------------------------------------------------------
// Report's Cashier Module: Verify Payment, Confirm Booking, Print Ticket, View Transactions.

Route::middleware(['auth', 'role:cashier'])->prefix('cashier')->name('cashier.')->group(function () {
    Route::get('/', CashierCounter::class)->name('counter');
});

// ---- Passenger ---------------------------------------------------------------
// Report's Passenger Module: Registration, Login, Search Route, View Schedule,
// Book Seat, Receive Digital Ticket, View Booking History.

Route::middleware(['auth', 'role:passenger'])->name('passenger.')->group(function () {
    Route::get('/book', BookingFlow::class)->name('book');
    Route::get('/my-bookings', BookingHistory::class)->name('bookings');
});

// ---- Shared (any authenticated role, ownership checked in the controller) ----

Route::middleware('auth')->get('/tickets/{booking}', [TicketController::class, 'show'])->name('tickets.show');
